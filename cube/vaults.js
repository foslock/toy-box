// The four vaults. Vault I is laid out by hand as the lesson; II–IV came out of
// `node cube/solve.mjs gen` (seeded search, kept for their routes) and are checked
// by `node cube/solve.mjs check`. Rooms are listed with their home cell [x,y,z]
// (z = 0 is the bottom floor), doors [N,E,S,W] in the room's own frame.

const L = (rooms) => {
  // fill any unlisted cell with a plain room
  const out = [];
  for (let z = 0; z < 3; z++) for (let y = 0; y < 3; y++) for (let x = 0; x < 3; x++) {
    const r = rooms.find(q => q.home[0] === x && q.home[1] === y && q.home[2] === z);
    out.push(r || { home: [x, y, z], doors: [(x + y + z) & 1, 0, 1 - ((x + y + z) & 1), 1], deco: (x * 3 + y * 5 + z) % 7 });
  }
  return out;
};

