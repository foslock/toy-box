function inside(poly, x, y) {
  let c = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i], [xj, yj] = poly[j];
    if ((yi > y) !== (yj > y) && x < (xj - xi) * (y - yi) / (yj - yi) + xi) c = !c;
  }
  return c;
}

// A grid of dots, cols × rows over the whole globe (cropped at 60°S and 84°N), each marked land or sea, with the
// kind of land it is: in the order the wheat takes it.
export const KINDS = ['arable', 'pasture', 'forest', 'desert', 'tundra', 'ice'];
export function dots(cols, rows, top = 84, bottom = -62) {
  const out = [];
  const polys = Object.entries(LAND), lakes = Object.values(LAKES);
  for (let r = 0; r < rows; r++) {
    const lat = top - (r + 0.5) * (top - bottom) / rows;
    for (let c = 0; c < cols; c++) {
      const lon = -180 + (c + 0.5) * 360 / cols;
      let where = null;
      for (const [name, p] of polys) if (inside(p, lon, lat)) { where = name; break; }
      if (where && lakes.some(p => inside(p, lon, lat))) where = null;
      out.push({ c, r, lon, lat, land: !!where, kind: where ? kindOf(where, lon, lat) : 'sea', h: hash(c, r) });
    }
  }
  return out;
}

