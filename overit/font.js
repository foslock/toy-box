export const GLYPHS = {};
for (const [ch, s] of Object.entries(G)) {
  const rows = s.split('|');
  GLYPHS[ch] = { w: rows[0].length, rows: rows.map(r => [...r].map(c => c === '#')) };
}

export function textWidth(str, scale = 1) {
  let w = 0;
  for (const ch of str.toUpperCase()) w += ((GLYPHS[ch] || GLYPHS['?']).w + 1) * scale;
  return Math.max(0, w - scale);
}

// Writes text into a Float32 intensity bitmap (cols × rows). Returns the width drawn.
export function drawText(bm, cols, rows, str, x, y, scale = 1, v = 1) {
  let cx = Math.round(x);
  y = Math.round(y);
  for (const ch of str.toUpperCase()) {
    const g = GLYPHS[ch] || GLYPHS['?'];
    for (let r = 0; r < 7; r++) for (let c = 0; c < g.w; c++) {
      if (!g.rows[r][c]) continue;
      for (let sy = 0; sy < scale; sy++) for (let sx = 0; sx < scale; sx++) {
        const px = cx + c * scale + sx, py = y + r * scale + sy;
        if (px >= 0 && py >= 0 && px < cols && py < rows) bm[py * cols + px] = Math.max(bm[py * cols + px], v);
      }
    }
    cx += (g.w + 1) * scale;
  }
  return cx - x;
}

// Splits text into lines that fit `maxW` dots.
export function wrap(str, maxW, scale = 1) {
  const out = [];
  for (const para of str.split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      const t = line ? line + ' ' + word : word;
      if (textWidth(t, scale) <= maxW || !line) line = t;
      else { out.push(line); line = word; }
    }
    out.push(line);
  }
  return out;
}
